#!/usr/bin/env python3
"""Regenerate sources/fr.animesama/src/variants.rs.

Anime-Sama's catalogue only lists works, while one work page can hold several scan
panels (spin-offs, colour / black and white, JoJo parts...). The source turns each
panel into its own Aidoku entry, so it needs to know which works have several panels
without opening every work page. This script crawls the scans catalogue once and
writes that table.

Usage:
    scripts/update-animesama-variants.py           # rewrite the table
    scripts/update-animesama-variants.py --check   # exit 1 if the table is stale
"""

import concurrent.futures
import json
import os
import pathlib
import re
import sys
import time
import urllib.request

# Same overrides as scripts/verify-animesama.sh.
BASE_URL = os.environ.get("ANIMESAMA_BASE_URL", "https://anime-sama.to")
USER_AGENT = os.environ.get("ANIMESAMA_USER_AGENT", "Mozilla/5.0 (Aidoku)")
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "sources/fr.animesama/src/variants.rs"
CARD = re.compile(r'class="as-carte as-carte-oeuvre" data-url="/catalogue/([^/"]+)')
# Same rules as parse_scan_panels() and keep_panel() in src/lib.rs.
PANEL = re.compile(r"""panneauScan\(\s*(["'])(.*?)\1\s*,\s*(["'])(.*?)\3\s*\)""")


def fetch(url: str) -> str:
    for attempt in range(3):
        try:
            request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read().decode("utf-8", "replace")
        except OSError:
            if attempt == 2:
                raise
            time.sleep(2)
    raise AssertionError("unreachable")


def catalogue_slugs() -> list[str]:
    slugs: list[str] = []
    page = 1
    while True:
        html = fetch(f"{BASE_URL}/catalogue/?type%5B%5D=Scans&page={page}")
        start, end = html.find('id="list_catalog"'), html.find('id="list_pagination"')
        for slug in CARD.findall(html[start:end]):
            if slug not in slugs:
                slugs.append(slug)
        if 'rel="next"' not in html[end:]:
            return slugs
        page += 1


def keep_panel(name: str, path: str) -> bool:
    name = name.lower()
    return not path.endswith("/va") and "toute les parties" not in name and "toutes les parties" not in name


def scan_panels(html: str) -> list[tuple[str, str]]:
    panels: list[tuple[str, str]] = []
    for line in html.splitlines():
        line = line.strip()
        if line.startswith(("//", "/*", "<!--")):
            continue
        match = PANEL.search(line)
        if not match:
            continue
        name, path = match.group(2), match.group(4)
        if name != "nom" and keep_panel(name, path) and all(p != path for _, p in panels):
            panels.append((name, path))
    return panels


def render(table: dict[str, list[tuple[str, str]]]) -> str:
    def lit(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    lines = [
        "//! Generated by scripts/update-animesama-variants.py, do not edit by hand.",
        "//! Works whose page lists several scan panels: (slug, [(panel name, panel path)]).",
        "",
        "#[rustfmt::skip]",
        "pub const VARIANTS: &[(&str, &[(&str, &str)])] = &[",
    ]
    for slug in sorted(table):
        panels = ", ".join(f"({lit(name)}, {lit(path)})" for name, path in table[slug])
        lines.append(f"    ({lit(slug)}, &[{panels}]),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    slugs = catalogue_slugs()
    print(f"{len(slugs)} works in the scans catalogue", file=sys.stderr)

    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        pages = pool.map(lambda slug: fetch(f"{BASE_URL}/catalogue/{slug}/"), slugs)
        table = {
            slug: panels
            for slug, panels in ((slug, scan_panels(html)) for slug, html in zip(slugs, pages))
            if len(panels) > 1
        }

    output = render(table)
    if check:
        if OUTPUT.read_text() != output:
            print(
                "Anime-Sama variants table is stale: run scripts/update-animesama-variants.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok variants table ({len(table)} works)")
        return 0

    OUTPUT.write_text(output)
    print(f"wrote {OUTPUT} ({len(table)} works)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
